#!/usr/bin/env python3
"""Write the module sources and the generated tests from the dr_libs headers.

- src/wav.cppm, src/flac.cppm, src/mp3.cppm (mcpplibs.mwrap.dr_libs.wav,
  .flac, .mp3) each export every type, enumerator and *_API function of one
  header by `export using` (the upstream globals, unchanged), and re-export
  the macros module, so each is complete on its own.
- src/dr_libs.cppm (mcpplibs.mwrap.dr_libs) re-exports the three and the
  macros module.
- src/macros.cppm (mcpplibs.mwrap.dr_libs.macros) holds, in
  mcpplibs::mwrap::dr_libs::macros under their own names, every object-like
  macro of the three headers as `inline constexpr` of the type of its own
  expansion (result codes, formats, flags, metadata block and picture types,
  limits, versions; the version strings as references to constexpr char
  arrays). The headers have no computation macro: their function-like macros
  are the stringification helpers, which stay macros.
- tests/macros_mix_test.cpp checks each mapping against the raw headers in a
  translation unit that includes them beside the import, and
  tests/{wav,flac,mp3}_surface_test.cpp name every entity of one submodule
  with only that submodule imported.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, surface  # noqa: E402

# Macros that stay macros, in <mwrap/dr_libs/macros.hpp> (which includes the three headers).
SIDE_HEADER = {}
for p in ('DRWAV', 'DRFLAC', 'DRMP3'):
    SIDE_HEADER |= {
        f'{p}_API': 'an attribute of declarations (`extern` here; dllimport/dllexport or visibility under ' + p + '_DLL)',
        f'{p}_PRIVATE': 'an attribute of the implementation\'s declarations (`static` here)',
        f'{p}_DLL_IMPORT': 'defined only under ' + p + '_DLL: an attribute',
        f'{p}_DLL_EXPORT': 'defined only under ' + p + '_DLL: an attribute',
        f'{p}_DLL_PRIVATE': 'defined only under ' + p + '_DLL: an attribute',
        f'{p}_STRINGIFY': 'stringification (`#x`)',
        f'{p}_XSTRINGIFY': 'stringification after expansion',
    }
SIDE_HEADER |= {
    'DRFLAC_DEPRECATED': 'an attribute of declarations',
    'DRMP3_INLINE': 'a function specifier (`__forceinline` / `inline __attribute__((always_inline))`)',
    'DRMP3_GNUC_INLINE_HINT': 'a function specifier (`inline` / `__inline__`)',
    'DRFLAC_64BIT': 'platform detection, defined only on 64-bit targets: for #ifdef',
    'DRFLAC_X64': 'platform detection, defined only on x86_64: for #ifdef',
    'DRFLAC_X86': 'platform detection, defined only on x86: for #ifdef',
    'DRFLAC_ARM': 'platform detection, defined only on ARM: for #ifdef',
}
# Defined under `#ifndef` with a default: always defined, so mapped (its value is the build's).
DEFAULTED = {'DR_FLAC_BUFFER_SIZE'}


def excluded(name: str) -> str | None:
    if re.fullmatch(r'dr_(wav|flac|mp3)_h', name):
        return 'include guard'
    return None


def all_macros(headers):
    out = {}
    for h in headers:
        out |= h.macros
    return out


def classify(headers):
    strings, constants = [], []
    for macro in all_macros(headers).values():
        if macro.name in SIDE_HEADER or excluded(macro.name):
            continue
        if macro.params is not None:
            sys.exit(f'{macro.header}: function-like macro {macro.name} is neither mapped nor listed')
        if macro.conditional and macro.name not in DEFAULTED:
            sys.exit(f'{macro.header}: {macro.name} is defined conditionally and not listed')
        if macro.name.endswith('_VERSION_STRING'):
            strings.append(macro.name)
        else:
            constants.append(macro.name)
    return strings, constants


INCLUDES = '#include <dr_wav.h>\n#include <dr_flac.h>\n#include <dr_mp3.h>'
GENERATED = '''// Generated by tools/gen_exports.py from the dr_libs headers (dr_wav 0.14.5,
// dr_flac 0.13.3, dr_mp3 0.7.3; commit fa931f3) — do not edit by hand.
//'''

SUBMODULE = {
    'wav': ('dr_wav', 'WAV, RIFX, RF64, Sony Wave64 and AIFF reading and writing: drwav_init*, '
            'drwav_init_write*, drwav_read_pcm_frames*, drwav_write_pcm_frames, metadata (smpl, '
            'inst, cue, acid, bext, LIST), the sample format conversions'),
    'flac': ('dr_flac', 'FLAC decoding, native and Ogg-encapsulated: drflac_open*, '
             'drflac_read_pcm_frames*, drflac_seek_to_pcm_frame, metadata blocks and their '
             'iterators (Vorbis comments, cuesheets)'),
    'mp3': ('dr_mp3', 'MPEG-1/2/2.5 Layer III decoding: drmp3_init*, drmp3_read_pcm_frames*, '
            'drmp3_seek_to_pcm_frame, seek tables, ID3/APE/Xing/LAME metadata, and the '
            'low-level frame decoder drmp3dec'),
}


def render_sub(h) -> str:
    lib, what = SUBMODULE[h.short]
    out = [f'''{GENERATED}
// mcpplibs.mwrap.dr_libs.{h.short} — {lib} as a C++ module: {what}.
// Every exported name is the upstream global of <{h.name}>, unchanged. Every
// enum of the header is named by its typedef, so its enumerators have linkage
// and are exported as they are. Re-exports mcpplibs.mwrap.dr_libs.macros (the
// header's constants: result codes, formats, flags …), so this module is
// complete on its own. The library is compat.dr_libs, built from the same
// commit.
module;
#include <{h.name}>

export module mcpplibs.mwrap.dr_libs.{h.short};

export import mcpplibs.mwrap.dr_libs.macros;
''']
    out.append(f'// types ({len(h.types)})')
    out += [f'export using ::{n};' for n in h.types]
    if h.tags:
        out.append(f'\n// struct tags ({len(h.tags)})')
        out += [f'export using ::{n};' for n in h.tags]
    out.append(f'\n// enumerators ({len(h.enumerators)})')
    out += [f'export using ::{n};' for n in h.enumerators]
    out.append(f'\n// functions ({len(h.functions)})')
    out += [f'export using ::{n};' for n in h.functions]
    return '\n'.join(out) + '\n'


ROOT = GENERATED + '''
// mcpplibs.mwrap.dr_libs — dr_wav, dr_flac and dr_mp3 as C++ modules: the
// whole API of <dr_wav.h>, <dr_flac.h> and <dr_mp3.h>, the upstream globals
// unchanged, and their constants. Each header is also a module of its own
// (mcpplibs.mwrap.dr_libs.wav, .flac, .mp3). The library is compat.dr_libs.
export module mcpplibs.mwrap.dr_libs;

export import mcpplibs.mwrap.dr_libs.wav;
export import mcpplibs.mwrap.dr_libs.flac;
export import mcpplibs.mwrap.dr_libs.mp3;
export import mcpplibs.mwrap.dr_libs.macros;
'''

MACROS_HEADER = GENERATED + '''
// mcpplibs.mwrap.dr_libs.macros — the macros of <dr_wav.h>, <dr_flac.h> and
// <dr_mp3.h> that a named module cannot export as they are, under the
// original names in mcpplibs::mwrap::dr_libs::macros: every object-like macro
// (DRWAV_SUCCESS …, DR_WAVE_FORMAT_*, DRWAV_SEQUENTIAL,
// DRFLAC_METADATA_BLOCK_TYPE_*, DRFLAC_PICTURE_TYPE_*, DRMP3_MAX_*,
// DR_FLAC_BUFFER_SIZE, DRMP3_UINT64_MAX, the *_TRUE / *_FALSE and
// *_VERSION_* macros) as `inline constexpr`, each of the type its macro
// expands to (DRWAV_SUCCESS is an `int`, as 0 is; DRMP3_UINT64_MAX a
// `drmp3_uint64`), the version strings as references to constexpr char
// arrays. The headers have no computation macro.
//
// Attributes, the stringification helpers and the platform detection macros
// stay macros, in <mwrap/dr_libs/macros.hpp>, included before the import.
// tools/check_exports.py accounts for every macro.
module;
''' + INCLUDES + '''
'''


def render_macros(headers) -> str:
    strings, constants = classify(headers)
    out = [MACROS_HEADER]
    out.append('export module mcpplibs.mwrap.dr_libs.macros;\n')
    out.append('// The headers\' values, taken while their macros are defined (module linkage).')
    out.append('namespace mwrap_dr_libs_capture {')
    out += [f'inline constexpr auto value_{n} = {n};' for n in constants]
    out += [f'inline constexpr char value_{n}[] = {n};' for n in strings]
    out.append('}  // namespace mwrap_dr_libs_capture\n')
    out.append('// Every mapped name, so the definitions below are not rewritten.')
    out += [f'#undef {n}' for n in constants + strings]
    out.append('\nnamespace c = mwrap_dr_libs_capture;\n')
    out.append('export namespace mcpplibs::mwrap::dr_libs::macros {')
    macros = all_macros(headers)
    for h in headers:
        mine = [n for n in constants if macros[n].header == h.name]
        mine_s = [n for n in strings if macros[n].header == h.name]
        out.append(f'\n// ── <{h.name}>: {len(mine)} constants, {len(mine_s)} string ' + '─' * max(0, 44 - len(h.name)))
        out += [f'inline constexpr auto {n} = c::value_{n};' for n in mine]
        out += [f'inline constexpr auto& {n} = c::value_{n};' for n in mine_s]
    out.append('\n}  // namespace mcpplibs::mwrap::dr_libs::macros')
    return '\n'.join(out) + '\n'


TEST_HEADER = GENERATED + '''
// Every mapping against the raw headers, in one translation unit that
// includes <mwrap/dr_libs/macros.hpp> (that is, <dr_wav.h>, <dr_flac.h> and
// <dr_mp3.h>) beside the import: each constant has its macro's type and value
// (the macro is set aside with push_macro around the comparison: while it is
// defined it expands even inside `m::NAME`), each version string its macro's
// characters.
#include <mwrap/dr_libs/macros.hpp>
#include <gtest/gtest.h>

import std;
import mcpplibs.mwrap.dr_libs;

namespace m = mcpplibs::mwrap::dr_libs::macros;
'''


def render_test(headers) -> str:
    strings, constants = classify(headers)
    out = [TEST_HEADER]
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    for n in constants:
        out.append(f'constexpr auto raw_{n} = {n};')
    for n in strings:
        out.append(f'using raw_type_{n} = decltype({n});')
        out.append(f'constexpr std::string_view raw_{n} = {n};')
    for n in constants:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<decltype(m::{n}), decltype(raw_{n})> && m::{n} == raw_{n});',
                f'#pragma pop_macro("{n}")']
    for n in strings:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<std::remove_cvref_t<decltype(m::{n})>, std::remove_cvref_t<raw_type_{n}>>);',
                f'static_assert(std::string_view(m::{n}) == raw_{n});',
                f'#pragma pop_macro("{n}")']
    out.append('''
// The version strings are the linked library's own.
TEST(Macros, VersionStringsAreTheLibrarys) {''')
    for n, fn in (('DRWAV_VERSION_STRING', 'drwav_version_string'), ('DRFLAC_VERSION_STRING', 'drflac_version_string'),
                  ('DRMP3_VERSION_STRING', 'drmp3_version_string')):
        out.append(f'    EXPECT_EQ(std::string_view({fn}()), raw_{n});')
    out.append('}')
    out.append(f'\nTEST(Macros, Count) {{ EXPECT_EQ({len(constants)} + {len(strings)}, {len(constants) + len(strings)}); }}')
    return '\n'.join(out) + '\n'


SURFACE_HEADER = GENERATED + '''
// mcpplibs.mwrap.dr_libs.{short} alone — no header, no other module: every
// type, enumerator and function of <{name}> is named through the import, so
// the submodule is complete on its own.
import std;
import mcpplibs.mwrap.dr_libs.{short};

// types ({types})
'''


def render_surface(h) -> str:
    out = [SURFACE_HEADER.format(short=h.short, name=h.name, types=len(h.types))]
    out += [f'using t_{n} = ::{n};' for n in h.types]
    out.append(f'\n// enumerators ({len(h.enumerators)}), each of its enum')
    out += [f'static_assert(std::is_same_v<decltype(::{n}), ::{t}>);' for n, t in h.enumerators.items()]
    out.append(f'\n// functions ({len(h.functions)})')
    out.append('using any_function = void (*)();')
    out.append('const any_function functions[] = {')
    out += [f'    reinterpret_cast<any_function>(&::{n}),' for n in h.functions]
    out.append('};')
    out.append(f'''
int main() {{
    for (any_function f : functions)
        if (f == nullptr) return 1;
    std::println("mcpplibs.mwrap.dr_libs.{h.short}: {len(h.types)} types, {len(h.enumerators)} enumerators, {len(h.functions)} functions");
    return 0;
}}''')
    return '\n'.join(out) + '\n'


def outputs(root: Path) -> dict[Path, str]:
    headers = surface(fetch(root))
    out = {root / 'src/dr_libs.cppm': ROOT, root / 'src/macros.cppm': render_macros(headers),
           root / 'tests/macros_mix_test.cpp': render_test(headers)}
    for h in headers:
        out[root / f'src/{h.short}.cppm'] = render_sub(h)
        out[root / f'tests/{h.short}_surface_test.cpp'] = render_surface(h)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, text in outputs(root).items():
        # Text mode: a checkout with CRLF line ends (Windows) reads the same.
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue  # unchanged: the timestamp is kept, nothing rebuilds
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
